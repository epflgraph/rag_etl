"""Notebooks: Jupyter notebooks (.ipynb) turned into Markdown.

The notebook is exported with nbconvert, style and script tags stripped
from its HTML outputs, and the images it references replaced by their
ALT text, generated by a vision model with the client the caller hands
over.
"""

from __future__ import annotations

import re

from pathlib import Path

import nbformat
from nbconvert import MarkdownExporter
from nbconvert.preprocessors import Preprocessor

from ragtools.images import ALT_TEXT_PROMPT
from ragtools.llm import RCPClient


def convert_ipynb_to_md(ipynb_path: str | Path, md_path: str | Path, llm: RCPClient, vision_model: str) -> None:
    """
    Convert a Jupyter Notebook (.ipynb) to a Markdown (.md) file.

    Parameters:
        ipynb_path (str or Path): Path to the input Jupyter notebook file.
        md_path (str or Path): Path for the output Markdown file.
        llm (RCPClient): Model client the ALT texts are generated with.
        vision_model (str): Vision model the ALT texts are generated with.
    """

    # Normalise to pathlib Paths
    ipynb_path = Path(ipynb_path)
    md_path = Path(md_path)

    # Read notebook
    with open(ipynb_path, "r", encoding="utf-8") as f:
        notebook_node = nbformat.read(f, as_version=4)

    # Preprocessor to clean style and script tags
    class CleanHTMLTagsPreprocessor(Preprocessor):
        TAG_RE = re.compile(
            r"<(style|script).*?>.*?</\1>",
            flags=re.DOTALL | re.IGNORECASE,
        )

        def preprocess_cell(self, cell, resources, index):
            # Remove from HTML outputs
            if cell.cell_type == "code" and "outputs" in cell:
                for output in cell.outputs:
                    if "text/html" in output.get("data", {}):
                        html = output["data"]["text/html"]
                        output["data"]["text/html"] = self.TAG_RE.sub("", html)

            # Optional: also clean markdown cells
            if cell.cell_type == "markdown":
                cell.source = self.TAG_RE.sub("", cell.source)

            return cell, resources

    # Export to markdown
    markdown_exporter = MarkdownExporter()
    markdown_exporter.register_preprocessor(CleanHTMLTagsPreprocessor(), enabled=True)
    text, _ = markdown_exporter.from_notebook_node(notebook_node)

    # Replace Markdown images (![alt](src))
    def md_image_replace(match):
        alt, src = match.group(1), match.group(2)
        p = (md_path.parent / src).resolve()

        if p.exists():
            alt = llm.vision(ALT_TEXT_PROMPT, [str(p)], model=vision_model, name="generate-alt-text", enable_thinking=False)

        return f"![{alt}]({src})"

    md_image_re = re.compile(r"!\[(.*?)\]\((.*?)\)")
    text = md_image_re.sub(md_image_replace, text)

    # Replace HTML images (<img...)
    def html_image_replace(m):
        tag, src = m.group(0), m.group(1)
        p = (md_path.parent / src).resolve()

        if p.exists():
            alt = llm.vision(ALT_TEXT_PROMPT, [str(p)], model=vision_model, name="generate-alt-text", enable_thinking=False)
        else:
            alt_match = re.search(r'alt="([^"]*)"', tag, re.IGNORECASE)
            alt = alt_match.group(1) if alt_match else ""

        return f"![{alt}]({src})"

    html_image_re = re.compile(r'<img\s+[^>]*src="([^"]+)"[^>]*>', re.IGNORECASE)
    text = html_image_re.sub(html_image_replace, text)

    # Write md file
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(text, encoding="utf-8")
